// Glossary lint. Run with: npm run lint:glossary
//
// REMEDIATION_PLAN Phase 1.2. A lesson may not use a domain or automation term
// before the lesson that teaches it.
//
// WHY THIS EXISTS
//
// A 2026-08-22 audit found exactly ONE plain-English gloss in the entire
// 120-lesson curriculum (a parenthetical in module-01 covering hub, MWh, and
// settled price). Meanwhile module-02 used "three-way match" 17 times,
// "tolerance" 23 times, "PO" 18 times and "receipt" 20 times without defining
// any of them, and module-03 used "SLA" 169 times without ever saying what it
// stands for.
//
// The proof this mattered: the product OWNER, reading a summary of his own
// curriculum, had to ask what "overcharge" meant. Not a gap in the reader - the
// vocabulary was generated by a builder with no way to notice it was assuming
// knowledge, and no gate checked for it. Six more specialist domains (month-end
// close, CRM hygiene, order flow, evidence chain-of-custody, campaign ops,
// incident response) are queued behind modules 4-10.
//
// HOW IT WORKS
//
// Each module ships curriculum/<module>/glossary.json declaring the terms it
// introduces and the lesson responsible for teaching each. This lint reads the
// learner-visible text of every lesson and reports a term used before it is
// taught, using LESSON_PATH order within a module and registry order across
// modules.
//
// Terms carried by src/data/automationTaxonomy.json (the nine action-kind
// labels) are globally taught: the kind-of-action chip renders their gloss on
// every intro and every takeaway, so they are available from lesson one.
//
// THE RATCHET
//
// ENFORCED starts false so the baseline is visible without turning
// `npm run check` red before the glosses are written. REMEDIATION_PLAN Phase
// 4.1-4.2 writes the Rosetta openings and per-term glosses, then flips this to
// true. Reordering the modules (Phase 4.3) is safe because each module's
// Operations lesson re-glosses the shared operating terms.

import { readFileSync, readdirSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const lessonsDir = path.join(root, 'src', 'data', 'lessons')
const registry = JSON.parse(readFileSync(path.join(root, 'src', 'data', 'projects.json'), 'utf8'))
const taxonomy = JSON.parse(
  readFileSync(path.join(root, 'src', 'data', 'automationTaxonomy.json'), 'utf8')
)

const ENFORCED = false

let errors = 0
let warnings = 0
const report = (id, msg) => {
  if (ENFORCED) {
    console.log(`ERROR ${id}: ${msg}`)
    errors += 1
  } else {
    console.log(`warn  ${id}: ${msg}`)
    warnings += 1
  }
}

// Terms the app teaches everywhere via the kind-of-action chip and its tooltip.
const GLOBALLY_TAUGHT = new Set(
  taxonomy.actionKinds.map((k) => k.label.toLowerCase())
)

// LESSON_PATH per project gives within-module teaching order. It lives in
// src/data/projects/<id>/lessonMeta.json (the same file lint-map reads) and
// holds NODE ids, so map each to its taskId via workflowNodes.json.
function lessonPathFor(projectId) {
  const dir = path.join(root, 'src', 'data', 'projects', projectId)
  const metaFile = path.join(dir, 'lessonMeta.json')
  const nodesFile = path.join(dir, 'workflowNodes.json')
  if (!existsSync(metaFile) || !existsSync(nodesFile)) return null
  const meta = JSON.parse(readFileSync(metaFile, 'utf8'))
  const nodes = JSON.parse(readFileSync(nodesFile, 'utf8'))
  const taskIdOf = Object.fromEntries(nodes.map((n) => [n.id, n.taskId]))
  return (meta.LESSON_PATH || []).map((nodeId) => taskIdOf[nodeId]).filter(Boolean)
}

const projects = registry.map((p) => p.id)
const moduleOrder = Object.fromEntries(projects.map((id, i) => [id, i]))

// term -> { module, moduleIndex, teachesIn, nodeOrder, pattern }
const taught = []
for (const projectId of projects) {
  const file = path.join(root, 'curriculum', projectId, 'glossary.json')
  if (!existsSync(file)) continue
  const glossary = JSON.parse(readFileSync(file, 'utf8'))
  const order = lessonPathFor(projectId) || []
  for (const entry of glossary.terms || []) {
    const surfaces = [entry.term, ...(entry.aliases || [])]
    // Where in this module's teaching order the gloss appears. The taskId of
    // the teaching lesson, stripped of any tier suffix, indexes LESSON_PATH.
    const taskId = String(entry.teachesIn).replace(/-(medium|hard)$/, '')
    const idx = order.indexOf(taskId)
    taught.push({
      term: entry.term,
      surfaces,
      module: projectId,
      moduleIndex: moduleOrder[projectId],
      teachesIn: entry.teachesIn,
      teachOrder: idx === -1 ? Number.MAX_SAFE_INTEGER : idx,
      teachOrderKnown: idx !== -1,
    })
  }
}

if (taught.length === 0) {
  console.log('glossary lint: no curriculum/<module>/glossary.json found - nothing to check')
  process.exit(0)
}

// Word-boundary match, case-insensitive, longest surface first so "three-way
// match" is not reported as a bare "match".
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
for (const t of taught) {
  t.regex = new RegExp(
    `(^|[^a-zA-Z0-9-])(${t.surfaces.sort((a, b) => b.length - a.length).map(escape).join('|')})([^a-zA-Z0-9-]|$)`,
    'i'
  )
}

// Learner-visible text only. Author-facing keys (validation internals, ids) are
// excluded: a term inside a field name is not prose the learner reads.
function learnerText(lesson) {
  const parts = [
    lesson.title,
    lesson.subtitle,
    lesson.scenario,
    lesson.input,
    ...(lesson.instructions || []),
    lesson.intro?.heading,
    lesson.intro?.summary,
    ...(lesson.intro?.sections || []).flatMap((s) => [s.title, s.body]),
    lesson.takeaway?.heading,
    lesson.takeaway?.before,
    lesson.takeaway?.after,
    lesson.takeaway?.capability,
    ...(lesson.takeaway?.points || []),
  ]
  return parts.filter((x) => typeof x === 'string').join('\n')
}

const lessons = {}
for (const file of readdirSync(lessonsDir).filter((f) => f.endsWith('.json'))) {
  const lesson = JSON.parse(readFileSync(path.join(lessonsDir, file), 'utf8'))
  lessons[lesson.id] = lesson
}

const findings = []
let scanned = 0
const missingTeacher = []

for (const projectId of projects) {
  const order = lessonPathFor(projectId)
  if (!order) continue
  const mIdx = moduleOrder[projectId]
  for (let i = 0; i < order.length; i += 1) {
    const taskId = order[i]
    for (const suffix of ['', '-medium', '-hard']) {
      const lesson = lessons[taskId + suffix]
      if (!lesson) continue
      scanned += 1
      const text = learnerText(lesson)
      for (const t of taught) {
        if (GLOBALLY_TAUGHT.has(t.term.toLowerCase())) continue
        if (!t.regex.test(text)) continue
        // Taught in a later module?
        if (t.moduleIndex > mIdx) {
          findings.push({ lesson: lesson.id, term: t.term, why: `taught in ${t.module} (a later module)` })
          continue
        }
        // Same module, taught later in the path?
        if (t.moduleIndex === mIdx && t.teachOrderKnown && t.teachOrder > i) {
          findings.push({
            lesson: lesson.id,
            term: t.term,
            why: `taught in ${t.teachesIn}, which comes later in this module`,
          })
        }
      }
    }
  }
}

for (const t of taught) {
  if (!t.teachOrderKnown) {
    missingTeacher.push(`${t.module}: "${t.term}" names teachesIn "${t.teachesIn}", which is not on that module's LESSON_PATH`)
  }
}

console.log('glossary lint: a term may not be used before the lesson that teaches it')
console.log('')
console.log(`  ${taught.length} terms declared across ${new Set(taught.map((t) => t.module)).size} module(s); ${scanned} lessons scanned`)

if (missingTeacher.length) {
  console.log('')
  for (const m of missingTeacher) report('glossary', m)
}

// Group findings by term so the report names the fix, not 40 symptoms.
const byTerm = {}
for (const f of findings) (byTerm[f.term] || (byTerm[f.term] = [])).push(f)
const terms = Object.keys(byTerm).sort((a, b) => byTerm[b].length - byTerm[a].length)

if (terms.length) {
  console.log('')
  console.log(`  ${findings.length} use(s)-before-teaching across ${terms.length} term(s):`)
  for (const term of terms) {
    const list = byTerm[term]
    report(
      `term "${term}"`,
      `used before it is taught in ${list.length} lesson(s) - ${list[0].why}. ` +
        `e.g. ${list.slice(0, 3).map((f) => f.lesson).join(', ')}`
    )
  }
} else {
  console.log('')
  console.log('  no term is used before it is taught')
}

console.log('')
console.log(
  `glossary lint: ${errors} errors, ${warnings} warnings` +
    ` (${ENFORCED ? 'ENFORCED' : 'baseline only - ratchet in REMEDIATION_PLAN Phase 4.2'})`
)
if (errors > 0) process.exitCode = 1
